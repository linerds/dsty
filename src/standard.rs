/// Текст пункту.
pub fn clause(id: &str) -> Option<&'static str> {
    CLAUSES.iter().find(|(c, _)| *c == id).map(|(_, t)| *t)
}

/// Пункти з переліку правила: «7.1.20, 7.1.21», «7.4.1–7.4.5» (діапазон
/// охоплює всі відомі пункти між межами).
pub fn clauses_of(spec: &str) -> Vec<(&'static str, &'static str)> {
    let mut out = Vec::new();
    for part in spec.split(',').map(str::trim) {
        let (from, to) = match part.split_once('–') {
            Some((a, b)) => (a.trim(), b.trim()),
            None => (part, part),
        };
        let Some(start) = CLAUSES.iter().position(|(c, _)| *c == from) else {
            continue;
        };
        let end = CLAUSES
            .iter()
            .position(|(c, _)| *c == to)
            .unwrap_or(start)
            .max(start);
        for &(c, t) in &CLAUSES[start..=end] {
            if !out.iter().any(|(o, _)| *o == c) {
                out.push((c, t));
            }
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::rules::RULES;

    #[test]
    fn every_rule_clause_is_quoted() {
        for rule in RULES.iter().filter(|r| !r.clause.is_empty()) {
            for part in rule.clause.split(',').map(str::trim) {
                for id in part.split('–').map(str::trim) {
                    assert!(
                        clause(id).is_some(),
                        "немає тексту пункту {id} (правило {})",
                        rule.code
                    );
                }
            }
        }
    }

    #[test]
    fn ranges() {
        let ids: Vec<_> = clauses_of("7.4.1–7.4.5, 7.15.2")
            .into_iter()
            .map(|(c, _)| c)
            .collect();
        assert_eq!(ids, ["7.4.1", "7.4.2", "7.4.3", "7.4.4", "7.4.5", "7.15.2"]);
    }
}
